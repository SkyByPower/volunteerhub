def get_locale():
    if has_request_context():
        lang = session.get("lang")
        if lang in current_app.config["LANGUAGES"]:
            return lang
        best = request.accept_languages.best_match(current_app.config["LANGUAGES"])
        if best:
            return best
    return current_app.config.get("DEFAULT_LANGUAGE", "kk")


def t(key):
    pair = TRANSLATIONS.get(key)
    if pair is None:
        return key
    return pair[1] if get_locale() == "ru" else pair[0]


class LazyText:
    """Translation evaluated at render time (for WTForms labels and messages)."""

    def __init__(self, key):
        self.key = key

    def __str__(self):
        return t(self.key)

    def __html__(self):
        from markupsafe import escape
        return str(escape(str(self)))

    def __mod__(self, other):
        return str(self) % other

    def __len__(self):
        return len(str(self))


def init_i18n(app):
    @app.context_processor
    def inject_i18n():
        return {"t": t, "lang": get_locale()}

    @app.route("/lang/<code>")
    def set_language(code):
        if code in app.config["LANGUAGES"]:
            session["lang"] = code
        target = request.referrer or url_for("main.index")
        # only redirect back to our own host
        if not target.startswith(request.host_url):
            target = url_for("main.index")
        return redirect(target)
